CREATE TABLE IF NOT EXISTS benchmark_task (
  task_id VARCHAR(64) NOT NULL COMMENT '压测任务标识符',
  tenant_id VARCHAR(64) NOT NULL COMMENT '租户标识符',
  task_type VARCHAR(32) NOT NULL COMMENT '压测任务类型：BASELINE/COMPARISON/REGRESSION_GUARD',
  sql_text LONGTEXT DEFAULT NULL COMMENT '已提交 SQL 文本快照',
  sql_fingerprint VARCHAR(128) NOT NULL COMMENT '归一化 SQL 指纹',
  priority VARCHAR(16) NOT NULL COMMENT '任务优先级',
  target_engines_json JSON NOT NULL COMMENT '请求的目标引擎列表 JSON',
  concurrency INT DEFAULT NULL COMMENT '请求的压测并发数',
  duration_seconds INT DEFAULT NULL COMMENT '请求的压测持续秒数',
  ramp_up_seconds INT DEFAULT NULL COMMENT '请求的预热爬坡秒数',
  dataset_size_label VARCHAR(64) DEFAULT NULL COMMENT '数据集规模标签',
  readonly_required TINYINT(1) NOT NULL DEFAULT 1 COMMENT '只读护栏标志',
  shadow_environment_mode VARCHAR(32) NOT NULL COMMENT '影子环境要求模式',
  desensitization_requirement VARCHAR(32) NOT NULL COMMENT '脱敏要求模式',
  thresholds_json JSON NOT NULL COMMENT '阈值定义 JSON',
  status VARCHAR(16) NOT NULL COMMENT 'Task 状态：QUEUED/RUNNING/SUCCEEDED/FAILED/CANCELLED',
  current_phase VARCHAR(32) NOT NULL COMMENT '当前任务阶段',
  progress_percent INT NOT NULL DEFAULT 0 COMMENT '进度百分比',
  report_id VARCHAR(64) DEFAULT NULL COMMENT '可用时生成的报告标识符',
  error_code INT DEFAULT NULL COMMENT '失败码',
  error_message VARCHAR(512) DEFAULT NULL COMMENT '脱敏后的失败消息',
  error_suggested_action VARCHAR(512) DEFAULT NULL COMMENT '建议的后续处理动作',
  error_retryable TINYINT(1) DEFAULT NULL COMMENT '失败是否可重试',
  status_history_json JSON NOT NULL COMMENT '有序状态流转历史 JSON',
  submitted_at DATETIME(3) NOT NULL COMMENT '提交时间戳',
  started_at DATETIME(3) DEFAULT NULL COMMENT 'Worker 启动时间戳',
  finished_at DATETIME(3) DEFAULT NULL COMMENT '结束时间戳',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间戳',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后更新时间戳',
  PRIMARY KEY (task_id),
  KEY idx_benchmark_task_status_submitted (status, submitted_at),
  KEY idx_benchmark_task_tenant_time (tenant_id, create_time),
  KEY idx_benchmark_task_fingerprint (sql_fingerprint)
);

CREATE TABLE IF NOT EXISTS benchmark_task_report (
  report_id VARCHAR(64) NOT NULL COMMENT '压测报告标识符',
  task_id VARCHAR(64) NOT NULL COMMENT '关联压测 task标识符',
  tenant_id VARCHAR(64) NOT NULL COMMENT '租户标识符',
  task_type VARCHAR(32) NOT NULL COMMENT '压测任务类型',
  sql_fingerprint VARCHAR(128) NOT NULL COMMENT '归一化 SQL 指纹',
  generated_at DATETIME(3) NOT NULL COMMENT '报告生成时间戳',
  verdict VARCHAR(32) NOT NULL COMMENT '报告结论',
  engine_profiles_json JSON NOT NULL COMMENT '按引擎统计的压测指标 JSON',
  threshold_assessments_json JSON NOT NULL COMMENT '阈值评估 JSON',
  recommendations_json JSON NOT NULL COMMENT '推荐列表 JSON',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间戳',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '最后更新时间戳',
  PRIMARY KEY (report_id),
  UNIQUE KEY uk_benchmark_task_report_task_id (task_id),
  KEY idx_benchmark_task_report_tenant_time (tenant_id, create_time),
  KEY idx_benchmark_task_report_fingerprint (sql_fingerprint)
);
